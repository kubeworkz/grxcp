def cost_by_draw(w, kind, row):
    """What a row leaves on each draw: the five networks' mean."""
    return [b - a for a, b in zip(by_draw(w, kind, row, runs), by_draw(w, kind, "dark", runs))]


def same_runs(kind):
    """The runs told apart with no part that got right what the cycle with no source of their draw
    did, and how many there are."""
    pairs = [(a, b) for w in WORKLOADS for d in DRAWS for a, b in zip(RUN[w][kind][(NONE, d)], RUN[w][kind][("dark", d)])]
    return sum(a == b for a, b in pairs), len(pairs)


def weights(w, kind):
    """A kind's weights that are not zero, in the first layer and in the last: a mean over the runs."""
    cells = [mv for d in DRAWS for mv, _ in RAIL[w][kind][d]]
    return sum(c[0] for c in cells) / len(cells), sum(c[1] for c in cells) / len(cells)


