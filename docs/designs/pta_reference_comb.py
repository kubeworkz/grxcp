# ---- what follows from them ---------------------------------------------------------
def stat(xs):
    """Five figures' mean and standard error."""
    n = len(xs)
    m = sum(xs) / n
    return m, math.sqrt(sum((x - m) ** 2 for x in xs) / (n - 1) / n)


def spread(xs):
    """Some figures' standard deviation."""
    m = sum(xs) / len(xs)
    return math.sqrt(sum((x - m) ** 2 for x in xs) / (len(xs) - 1))


def runs(w, kind, row, draw):
    """A kind's five networks in a row on a draw: how often each is right, percent."""
    return RUN[w][kind][(row, draw)]


def partner(row, draw):
    """The row and draw a row is read over: the cycle with no source of its draw, which
    meets its noise; and for that row, the plan's draw."""
    return ("dark", PLAN) if row == "dark" else ("dark", draw)


def diffs(w, kind, row, draw):
    """What a row adds on a draw over the row it is read over, network by network:
    how often right there, less in the row."""
    return [p - x for p, x in zip(RUN[w][kind][partner(row, draw)], RUN[w][kind][(row, draw)])]


def acc(w, kind, row, draw):
    """How often a kind of network is right in a row on one draw."""
    return stat(runs(w, kind, row, draw))


def adds(w, kind, row, draw):
    """What a row adds on one draw."""
    return stat(diffs(w, kind, row, draw))


def by_net(w, kind, row, what=diffs):
    """A figure for each network: its mean over the draws."""
    return [sum(what(w, kind, row, d)[i] for d in DRAWS) / len(DRAWS) for i in range(SEEDS)]


def by_draw(w, kind, row, what=diffs):
    """A figure for each draw: the five networks' mean."""
    return [sum(what(w, kind, row, d)) / SEEDS for d in DRAWS]


def over(w, kind, row):
    """What a row ends over the row it is read over, over the draws: the mean, and its
    standard error from the five networks, each averaged over its draws."""
    return stat(by_net(w, kind, row))


def draw_sd(w, kind, row):
    """The standard deviation from draw to draw of that, the five networks' mean."""
    return spread(by_draw(w, kind, row))


def right(w, kind, row):
    """How often a kind of network is right in a row, over the draws."""
    return stat(by_net(w, kind, row, runs))


def right_sd(w, kind, row):
    """The standard deviation from draw to draw of that, the five networks' mean."""
    return spread(by_draw(w, kind, row, runs))


def more(w, kind, row, than):
    """What one row costs more than another on the same draws: how often right in
    the other, less in the row, network by network over the draws."""
    return stat([b - a for a, b in zip(by_net(w, kind, row, runs), by_net(w, kind, than, runs))])


def more_sd(w, kind, row, than):
    """The standard deviation from draw to draw of that, the five networks' mean."""
    return spread([b - a for a, b in zip(by_draw(w, kind, row, runs), by_draw(w, kind, than, runs))])


def leaves(w, kind, row=ALL):
    """What a corrected comb leaves in a row: the cycle with no source, less the row."""
    return more(w, kind, row, "dark")


def cost(w, kind, row):
    """The same network by network: what each of the five loses in a row, over its draws."""
    return [b - a for a, b in zip(by_net(w, kind, row, runs), by_net(w, kind, "dark", runs))]


def added(w, kind, some=FIVE):
    """Some rows told apart, added: what each leaves, summed network by network."""
    return stat([sum(xs) for xs in zip(*(cost(w, kind, row) for row in some))])


def rest(w, kind):
    """What the parts do to each other: all three at once, less the five added."""
    return stat([a - sum(xs) for a, *xs in zip(cost(w, kind, ALL), *(cost(w, kind, row) for row in FIVE))])


def seen(w, kind):
    """What the tile's way of seeing the correction adds: the row on the tile, less all
    three parts after the converter."""
    return more(w, kind, "tile", ALL)


def read_two_ways(w, kind):
    """The row on the model, less the read told apart: the same reading's error, as the
    model's own line has it and as a rewritten weight would."""
    return more(w, kind, "model", READ)


def rail(w, kind):
    """The rail, a layer, over the runs: of the first layer's weights that are not zero,
    how many the rail held back and the share that is; and the same of the last."""
    cells = [x for d in DRAWS for x in RAIL[w][kind][d]]
    n = len(cells)
    return (sum(h[0] for _, h in cells) / n, sum(h[0] / m[0] for m, h in cells) / n,
            sum(h[1] for _, h in cells) / n, sum(h[1] / m[1] for m, h in cells) / n)


def most_held(w, kind):
    """The most a run had held in the last layer, and the fewest."""
    held = [h[1] for d in DRAWS for _, h in RAIL[w][kind][d]]
    return max(held), min(held)


def reads(w, kind):
    """The read, over the runs: what the probe found on the lines; what its reading
    would leave, on the tile and on the model; and the share held at the rail.  Fractions."""
    cells = [x for d in DRAWS for x in READS[w][kind][d]]
    return tuple(sum(c[n] for c in cells) / len(cells) for n in range(4))


def grows(w, kind, row, layer):
    """How much larger a layer's own error is in a row than in the cycle with no source
    of its draw: the ratio less one, a mean over the runs.  Layer 1 is the first, 2 the last."""
    pairs = [(a[layer - 1], b[layer - 1]) for d in DRAWS for a, b in zip(ERR[w][kind][(row, d)], ERR[w][kind][("dark", d)])]
    return sum(a / b - 1 for a, b in pairs) / len(pairs)


def at_most(x, t=T95):
    """What a figure is put under, at one in twenty."""
    return x[0] + t * x[1]


def errors(x):
    """A difference in its own standard errors."""
    return x[0] / x[1] if x[1] else 0.0


def clear(x):
    """Whether five networks put a difference outside chance at one in twenty."""
    return abs(errors(x)) > T95


def clear_sets(what, kind=REFERENCE):
    """The data sets on which a figure is outside chance at one in twenty."""
    return [w for w in WORKLOADS if clear(what(w, kind))]


def largest(w, kind, some=FIVE):
    """The row told apart that leaves the most."""
    return max(some, key=lambda row: leaves(w, kind, row)[0])


def up(x):
    """A bound, rounded up to the hundredth."""
    return math.ceil(100 * x - 1e-9) / 100


def pm(x):
    return f"{x[0]:.2f} +-{x[1]:.2f}"


def dpm(x):
    return f"{x[0]:+.2f} +-{x[1]:.2f}"


def dpm3(x):
    return f"{x[0]:+.3f} +-{x[1]:.3f}"


def r2(x):
    return round(x[0], 2), round(x[1], 2)


def r3(x):
    return round(x[0], 3), round(x[1], 3)


