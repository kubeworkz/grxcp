# ---- what they come to -----------------------------------------------------------
def stat(xs):
    """Five figures' mean and standard error."""
    n = len(xs)
    m = sum(xs) / n
    return m, math.sqrt(sum((x - m) ** 2 for x in xs) / (n - 1) / n)


def spread(xs):
    """Some figures' standard deviation."""
    m = sum(xs) / len(xs)
    return math.sqrt(sum((x - m) ** 2 for x in xs) / (len(xs) - 1))


def runs(w, kind, row, draw):
    """A kind's five networks in a row on a draw: how often each is right, percent.
    A row is (what is on, how many images)."""
    return [c[0] for c in RUN[w][kind][row + (draw,)]]


def agrees(w, kind, row, draw):
    """The same five: how often the class the tile gives is the class the host gives."""
    return [c[HOST] for c in RUN[w][kind][row + (draw,)]]


def declares(w, kind, row, draw):
    """And how often it is the class the declared reference gives: the gate's."""
    return [c[DECLARED_CLASS] for c in RUN[w][kind][row + (draw,)]]


def partner(row, draw):
    """The row and draw a row is read over, at its own count of images: the format
    alone of its draw for the tile as budgeted, and the tile as budgeted of its draw
    for a cycle.  The format alone is read over the plan's draw, which it is."""
    core, images = row
    return {"format": (("format", images), PLAN), "budget": (("format", images), draw), "cycle": (("budget", images), draw)}[core]


def diffs(w, kind, row, draw):
    """What a row adds on a draw over the row it is read over, network by network."""
    return [p - x for p, x in zip(runs(w, kind, *partner(row, draw)), runs(w, kind, row, draw))]


def acc(w, kind, row, draw):
    return stat(runs(w, kind, row, draw))


def adds(w, kind, row, draw):
    return stat(diffs(w, kind, row, draw))


def by_net(w, kind, row, what=diffs):
    """A figure for each network: its mean over the draws."""
    return [sum(what(w, kind, row, d)[i] for d in DRAWS) / len(DRAWS) for i in range(SEEDS)]


def by_draw(w, kind, row, what=diffs):
    """A figure for each draw: the five networks' mean."""
    return [sum(what(w, kind, row, d)) / SEEDS for d in DRAWS]


def over(w, kind, row):
    """What a row adds over the row it is read over, over the draws: the mean, and its
    standard error from the five networks, each averaged over its draws."""
    return stat(by_net(w, kind, row))


def draw_sd(w, kind, row):
    return spread(by_draw(w, kind, row))


def right(w, kind, row):
    """How often a kind of network is right in a row, over the draws."""
    return stat(by_net(w, kind, row, runs))


def right_sd(w, kind, row):
    return spread(by_draw(w, kind, row, runs))


def agree(w, kind, row, what=agrees):
    """How often the tile's class is the host's in a row, over the draws; or with
    what=declares, the declared reference's."""
    return stat(by_net(w, kind, row, what))


def agree_sd(w, kind, row, what=agrees):
    return spread(by_draw(w, kind, row, what))


def declared(w, kind, row):
    """How often the tile's class is its declared reference's in a row, over the draws."""
    return agree(w, kind, row, declares)


def declared_right(w, kind, images=ALL):
    """How often the declared reference is right, percent: the five networks' mean."""
    return sum(c[0 if images == ALL else 1] for c in DECLARED[w][kind]) / SEEDS


def each_run(table, w, kind, row):
    """A table's cell for each of a row's 25 runs, network by network and then draw by draw."""
    return [table[w][kind][row + (d,)][n] for n in range(SEEDS) for d in DRAWS]


def least(w, kind, row, which=HOST):
    """The least any run agrees with its host, or with its declared reference."""
    return min(c[which] for c in each_run(RUN, w, kind, row))


def at_bar(w, kind, row, bar=GATE_CLASS, which=HOST):
    """The runs that agree with their host on the gate's share of the images or more; or
    with which=DECLARED_CLASS, with their declared reference, which is the gate."""
    return sum(c[which] >= bar for c in each_run(RUN, w, kind, row))


def at_gate(w, kind, row):
    """The runs of 25 that pass the gate on the class: the declared reference's, on 99.5%."""
    return at_bar(w, kind, row, GATE_CLASS, DECLARED_CLASS)


def error(w, kind, row, table=None):
    """A row's error over its runs, percent: its rms over the reference's rms, over the
    largest the reference is, and its largest over that, each a mean.  Against the
    declared format, or with table=GIVEN against the operands as given."""
    cells = each_run(GATE if table is None else table, w, kind, row)
    return tuple(100 * sum(c[n] for c in cells) / len(cells) for n in range(3))


def most(w, kind, row, table=None):
    """The most the largest error is in any run, percent of the largest the reference is."""
    return 100 * max(c[2] for c in each_run(GATE if table is None else table, w, kind, row))


def within(w, kind, row, table=None):
    """The runs within the gate's 1.0% on each rms and its 2.0% on the largest."""
    cells = each_run(GATE if table is None else table, w, kind, row)
    return tuple(sum(100 * c[n] <= bar for c in cells) for n, bar in ((0, GATE_RMS), (1, GATE_RMS), (2, GATE_MAX)))


def past(w, kind, row):
    """The converter's range over a row's runs: the runs with a sum past it; the most sums
    past it in a run; and the most the largest error is, percent of the largest the
    reference is, in the runs with none past it and in the runs with some."""
    pairs = list(zip(each_run(RUN, w, kind, row), each_run(GATE, w, kind, row)))
    some = [(r[2], 100 * g[2]) for r, g in pairs if r[2] > 0]
    none = [100 * g[2] for r, g in pairs if r[2] == 0]
    return len(some), max((s for s, _ in some), default=0), max(none, default=0.0), max((z for _, z in some), default=0.0)


def sums(row):
    """The sums a run takes off the tile: the last layer's outputs, one launch each."""
    return OUTPUTS * row[1]


def step(w, kind, n):
    """The step of a network's last converter, in the units its sums are in."""
    return 2 ** FULL[w][kind][n][0]


def peak(w, kind, n, images=ALL):
    """The largest a network's declared reference is."""
    return FULL[w][kind][n][1 if images == ALL else 2]


def reach(w, kind, images=ALL):
    """For each network, the largest its declared reference is over its converter's full scale."""
    return [peak(w, kind, n, images) / (TOP * step(w, kind, n)) for n in range(SEEDS)]


def beyond(w, kind, images=ALL):
    """The networks whose declared reference goes past their converter's full scale."""
    return sum(r > 1 for r in reach(w, kind, images))


def in_steps(w, kind, row, n, draw, which=1):
    """A run's error in steps of its converter: its rms (which=1) or its largest (2)."""
    return GATE[w][kind][row + (draw,)][n][which] * peak(w, kind, n, row[1]) / step(w, kind, n)


def steps(w, kind, row, which=1):
    """A row's rms error against its declared format, in steps of the converter: a mean
    over its 25 runs.  With which=2, its largest error."""
    xs = [in_steps(w, kind, row, n, d, which) for n in range(SEEDS) for d in DRAWS]
    return sum(xs) / len(xs)


def of_top(w, kind, row, which=1):
    """The same as a share of the converter's full scale, percent."""
    return 100 * steps(w, kind, row, which) / TOP


def top_within(w, kind, row):
    """The runs whose rms is within the gate's 1.0% of the converter's full scale, and
    whose largest error is within its 2.0%."""
    return tuple(sum(100 * in_steps(w, kind, row, n, d, which) / TOP <= bar for n in range(SEEDS) for d in DRAWS)
                 for which, bar in ((1, GATE_RMS), (2, GATE_MAX)))


def sigmas(w, kind, row):
    """A row's largest error in its own rms errors: a mean over its runs."""
    cells = each_run(GATE, w, kind, row)
    return sum(c[2] / c[1] for c in cells) / len(cells)


def errors(x):
    """A difference in its own standard errors."""
    return x[0] / x[1] if x[1] else 0.0


def clear(x):
    """Whether five networks put a difference outside chance at one in twenty."""
    return abs(errors(x)) > T95


def span(xs):
    return min(xs), max(xs)


