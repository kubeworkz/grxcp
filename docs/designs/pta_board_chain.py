SPAN = 2 * TOP                                 # 254 steps: the converter's range with both its signs


def span_within(w, kind, row):
    """The runs whose rms is within the gate's 1.0% of the converter's whole span, and
    whose largest error is within its 2.0%."""
    return tuple(sum(100 * in_steps(w, kind, row, n, d, which) / SPAN <= bar for n in range(SEEDS) for d in DRAWS)
                 for which, bar in ((1, GATE_RMS), (2, GATE_MAX)))


def total(what, row, n=None):
    """A count over the three data sets and both kinds: 150 runs."""
    return sum(what(w, k, row) if n is None else what(w, k, row)[n] for w in WORKLOADS for k in KINDS)


def lost(w, kind, row):
    """What a row loses against the host: the host's accuracy less the row's, network by
    network over the draws."""
    return stat([h - x for h, x in zip(HOSTS[w][kind], by_net(w, kind, row, runs))])


def apart(w, kind, row, what=agrees):
    """How often the class the tile gives is not the host's, percent; or not its declared
    reference's."""
    return 100 - agree(w, kind, row, what)[0]


def format_share(w, kind, images=ALL):
    """Of the images the tile as budgeted and its host give different classes, the share
    the format alone already does."""
    return apart(w, kind, ("format", images)) / apart(w, kind, ("budget", images))


def tail(n):
    """Where the largest of n figures with Gaussian noise on them sits, in their rms:
    about the root of twice the log of n."""
    return math.sqrt(2 * math.log(n))


def unclipped(row):
    """The largest error of every run of a row that had no sum past its converter's range,
    percent of the largest the reference is, over the three data sets and both kinds."""
    return [100 * g[2] for w in WORKLOADS for k in KINDS for r, g in zip(each_run(RUN, w, k, row), each_run(GATE, w, k, row)) if r[2] == 0]


def all_largest(row):
    """Every run's largest error in a row, percent of the largest the reference is."""
    return [100 * g[2] for w in WORKLOADS for k in KINDS for g in each_run(GATE, w, k, row)]


def clipped(images=ALL):
    """The networks whose format-alone run has a sum past its converter's range: for each,
    its reach, the sums past the range, and its largest error, percent."""
    row = ("format", images, PLAN)
    return [(reach(w, k, images)[n], RUN[w][k][row][n][2], 100 * GATE[w][k][row][n][2])
            for w in WORKLOADS for k in KINDS for n in range(SEEDS) if RUN[w][k][row][n][2] > 0]


def most_past():
    """The largest share of a run's sums that is past its converter's range, in any run."""
    return max(r[2] / sums(row) for w in WORKLOADS for k in KINDS for row in BASES for r in each_run(RUN, w, k, row))


def pairs(what, fmt="{:.2f}"):
    """A figure for the networks trained before and for the reference on each data set,
    as the readings print it."""
    v = [fmt.format(what(w, k)) for w in WORKLOADS for k in KINDS]
    return f"{v[0]} and {v[1]} on MNIST, {v[2]} and {v[3]} on Fashion-MNIST and {v[4]} and {v[5]} on the inverted set"


def lohi(what, row, fmt="{:.2f}", kinds=KINDS):
    """A figure's least and most over the data sets and kinds, as the readings print it."""
    lo, hi = every(what, row, kinds)
    return f"{fmt.format(lo)} to {fmt.format(hi)}"


