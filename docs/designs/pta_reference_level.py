def db(x):
    """A line that far over its level, in decibels."""
    return 10 * math.log10(1 + x)


def times(w, kind):
    """What lines 40% off cost over what lines 20% off do: twice as far from level."""
    return over(w, kind, ("lit", LEVELS[2]))[0] / over(w, kind, ("lit", LEVELS[1]))[0]


def up(x):
    """A bound, to the hundredth above it: 'within' has to be true."""
    return math.ceil(100 * x - 1e-9) / 100


def widest(kind, rows):
    """The read row furthest from the level row of its draw, in the mean over the draws: how far, on any set."""
    return max(abs(over(w, kind, row)[0]) for w in WORKLOADS for row in rows)


def more_nets():
    """The hand check's seven more draws, MNIST and the reference networks: what a
    read on level lines buys each network, its mean over them."""
    return [sum(MORE[("read", d)][i] - MORE[("level", d)][i] for d in MORE_DRAWS) / len(MORE_DRAWS) for i in range(SEEDS)]


def more(what):
    """That over the five networks, or draw by draw."""
    by = [sum(MORE[("read", d)][i] - MORE[("level", d)][i] for i in range(SEEDS)) / SEEDS for d in MORE_DRAWS]
    return stat(more_nets()) if what == "nets" else by


def ten():
    """And over all ten draws, the mode's three and the hand check's seven: each
    network's mean over the ten."""
    a, b, n = by_net(MNIST, REFERENCE, ("read", 0.0, SHOTS), bought), more_nets(), len(DRAWS) + len(MORE_DRAWS)
    return stat([(len(DRAWS) * x + len(MORE_DRAWS) * y) / n for x, y in zip(a, b)])


def tpm(x):
    """To the thousandth: for differences of an image or two in ten thousand."""
    return f"{x[0]:+.3f} +-{x[1]:.3f}"


def clear_read():
    """The read rows five networks put off the level row of their draw at one in twenty."""
    rows = SIXTEEN + (LEVEL_READ, ONE, SIXTY_FOUR)
    return [(w, k, row) for w in WORKLOADS for k in KINDS for row in rows if clear(over(w, k, row))]


def cells_clear():
    """The cells those are in: a data set's kind of network."""
    return sorted({(w, k) for w, k, row in clear_read()})


def apart():
    """The sixteen-shot rows of a network on a draw take the same probe draws,
    whatever the lines' level: the widest any comb's four figures for what was
    left are apart, rms."""
    rows = SIXTEEN + (LEVEL_READ,)
    return max(max(LINES[(row, d)][n][1] for row in rows) - min(LINES[(row, d)][n][1] for row in rows) for d in DRAWS for n in range(SEEDS))


def most_clear():
    """The furthest any of those is from the level row, in the mean.  Nothing, if none is clear."""
    return max((abs(over(w, k, row)[0]) for w, k, row in clear_read()), default=0.0)


