# ---- what follows from them ---------------------------------------------------------
def stat(xs):
    """Five figures' mean and standard error."""
    n = len(xs)
    m = sum(xs) / n
    return m, math.sqrt(sum((x - m) ** 2 for x in xs) / (n - 1) / n)


def spread(xs):
    """Some figures' standard deviation."""
    m = sum(xs) / len(xs)
    return math.sqrt(sum((x - m) ** 2 for x in xs) / (len(xs) - 1))


def runs(w, kind, row, draw):
    """A kind's five networks in a row on a draw: how often each is right, percent."""
    return RUN[w][kind][(row, draw)]


def is_read(row):
    return row in READ


def unread(row):
    """The row a read row was read from."""
    assert is_read(row), row
    return HELD if row == HELD_READ else ("lit", row[1])


def partner(row, draw):
    """The row and draw a row is read over, which meets its noise: the level row of
    its draw for a lit row, read or not; the as-budgeted row of its draw for the
    level row and the two held rows; and the plan's for the as-budgeted row."""
    if row == "budget":
        return ("budget", PLAN)
    if row in (LEVEL, HELD, HELD_READ):
        return ("budget", draw)
    return (LEVEL, draw)


def diffs(w, kind, row, draw):
    """What a row adds on a draw over the row it is read over, network by network:
    how often right there, less in the row."""
    return [p - x for p, x in zip(RUN[w][kind][partner(row, draw)], RUN[w][kind][(row, draw)])]


def bought(w, kind, row, draw):
    """What a read buys on a draw, network by network: how often right in the read
    row, less in the row it was read from."""
    return [x - u for x, u in zip(RUN[w][kind][(row, draw)], RUN[w][kind][(unread(row), draw)])]


def acc(w, kind, row, draw):
    """How often a kind of network is right in a row on one draw."""
    return stat(runs(w, kind, row, draw))


def adds(w, kind, row, draw):
    """What a row adds on one draw."""
    return stat(diffs(w, kind, row, draw))


def by_net(w, kind, row, what=diffs):
    """A figure for each network: its mean over the draws."""
    return [sum(what(w, kind, row, d)[i] for d in DRAWS) / len(DRAWS) for i in range(SEEDS)]


def by_draw(w, kind, row, what=diffs):
    """A figure for each draw: the five networks' mean."""
    return [sum(what(w, kind, row, d)) / SEEDS for d in DRAWS]


def over(w, kind, row):
    """What a row adds, over the draws: the mean, and its standard error from the
    five networks, each averaged over its draws."""
    return stat(by_net(w, kind, row))


def draw_sd(w, kind, row):
    """The standard deviation from draw to draw of what a row adds, the five networks' mean."""
    return spread(by_draw(w, kind, row))


def right(w, kind, row):
    """How often a kind of network is right in a row, over the draws."""
    return stat(by_net(w, kind, row, runs))


def right_sd(w, kind, row):
    """The standard deviation from draw to draw of that, the five networks' mean."""
    return spread(by_draw(w, kind, row, runs))


def buys(w, kind, row):
    """What a read buys, over the draws: the mean, and its standard error from the
    five networks, each averaged over its draws."""
    return stat(by_net(w, kind, row, bought))


def buys_sd(w, kind, row):
    """The standard deviation from draw to draw of that, the five networks' mean."""
    return spread(by_draw(w, kind, row, bought))


def lost(w, kind, row):
    """What the tile costs a network in a row, over the draws: its accuracy on its host less there."""
    return stat([h - x for h, x in zip(HOSTS[w][kind], by_net(w, kind, row, runs))])


def adds_less(w, row):
    """What a row adds to a reference network over the draws, less what it adds to
    the one trained before of the same seed."""
    return stat([r - b for r, b in zip(by_net(w, REFERENCE, row), by_net(w, BEFORE, row))])


def worst(w, kind, row):
    """The most a row adds to any one network on any one draw, and the least."""
    xs = [x for d in DRAWS for x in diffs(w, kind, row, d)]
    return max(xs), min(xs)


# ---- the lines themselves ---------------------------------------------------------
def lines(row):
    """A read row's fifteen combs: what each was off by, rms, and what the probe left."""
    return [x for d in DRAWS for x in LINES[(row, d)]]


def found(row):
    """What was there, a mean over the fifteen combs of each one's rms."""
    xs = [f for f, _ in lines(row)]
    return sum(xs) / len(xs)


def left(row):
    """What the probe left, the same mean."""
    xs = [l for _, l in lines(row)]
    return sum(xs) / len(xs)


def left_span(row):
    """The least and the most it left on any one comb."""
    xs = [l for _, l in lines(row)]
    return min(xs), max(xs)


def shot_noise():
    """The source's noise on one shot of one row, rms: the lines together and the line on its own."""
    return math.hypot(TOGETHER, A_LINE)


def should_leave(shots):
    """What a probe of that many shots a row should leave on a line, rms: the
    source's noise over the root of the shots the line gets, a row on every bus,
    and the rounding of the step."""
    return math.hypot(shot_noise() / math.sqrt(shots * BUSES), STEP / math.sqrt(12))


def shots_for(target):
    """The fewest shots a row that should leave a line within a target, rms.  None
    if no number of shots would: the step's rounding alone is over it."""
    if STEP / math.sqrt(12) >= target:
        return None
    p = 1
    while should_leave(p) > target:
        p += 1
    return p


def below_dark(level):
    """The share of a Gaussian comb's lines that such an rms puts at less than no light."""
    return 0.5 * math.erfc(1 / (level * math.sqrt(2)))


# ---- what the probe takes ---------------------------------------------------------
ROWS = interruption.ROWS
PATTERNS = 2                                   # the rows of one parity, then of the other


def probe_shots(shots=SHOTS):
    """Its shots: every row, that many times."""
    return shots * ROWS


def probe_beats(shots=SHOTS, each_repeat=False):
    """The probe in beats, on one bank: its patterns programmed, its shots, and the
    bank's working weights programmed again.  As a chip would do it, a pattern is
    programmed once; grx930's harness programs one every repeat, which is the
    other count."""
    written = PATTERNS * (shots if each_repeat else 1)
    return written * interruption.t_w() + probe_shots(shots) * interruption.t_s() + interruption.restore(banks=1)


def errors(x):
    """A difference in its own standard errors."""
    return x[0] / x[1] if x[1] else 0.0


def clear(x):
    """Whether five networks put a difference outside chance at one in twenty."""
