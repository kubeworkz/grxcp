def fix(x, h):
    return ("fix", x, h)


def more_bits(w, kind, x):
    """What the DAC's two more bits buy: how often right with the weights written at
    8 bits, less at the tile's 6, network by network over the draws."""
    return stat([a - b for a, b in zip(by_net(w, kind, fix(x, W8), runs), by_net(w, kind, fix(x, W6), runs))])


def back(w, kind, row):
    """The share of what the comb cost that a correction takes back."""
    return buys(w, kind, row)[0] / over(w, kind, alone(row))[0]


def furthest(kind, rows):
    """The furthest any of some rows ends from the level row, in the mean, on any set."""
    return max(abs(over(w, kind, row)[0]) for w in WORKLOADS for row in rows)


LO, HI = LEVELS


def tenth(w, h, x=HI):
    """Whether a place ends within a tenth of level lines on a set, the reference networks, to the hundredth."""
    return round(abs(over(w, REFERENCE, fix(x, h))[0]), 2) <= WITHIN


def tenth_sets():
    """On how many of the three sets each place but the weights at 8 bits does, at 20%."""
    return [sum(tenth(w, h) for w in WORKLOADS) for h in PLACES if h != W8]


def relaxed(w, kind, h=W8):
    """A comb 20% off and corrected, less a comb 5% off and left alone: what each adds
    over level lines, network by network.  The plan's row is the second."""
    return stat([a - b for a, b in zip(by_net(w, kind, fix(HI, h)), by_net(w, kind, ("lit", LO)))])


def clear_low():
    """At the plan's 5%: the places and sets where what a correction buys the reference
    networks is outside chance at one in twenty."""
    return [(w, h) for w in WORKLOADS for h in PLACES if clear(buys(w, REFERENCE, fix(LO, h)))]


