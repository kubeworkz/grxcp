def read_beats():
    """The read of the lines: pta_reference_level.py's count, on one bank."""
    return level.probe_beats(SHOTS)


def calibration_beats():
    """An interruption at its most, as pta_interruption.py counts it, and the read after it."""
    return interruption.MOST + read_beats()


def at_most(x, t=T95):
    """What a figure is put under, at one in twenty."""
    return x[0] + t * x[1]


def at_least(x, t=T95):
    """And over."""
    return x[0] - t * x[1]


def errors(x):
    """A difference in its own standard errors."""
    return x[0] / x[1] if x[1] else 0.0


def clear(x):
    """Whether five networks put a difference outside chance at one in twenty."""
    return abs(errors(x)) > T95


def up(x):
    """A bound, rounded up to the hundredth."""
    return math.ceil(100 * x - 1e-9) / 100


