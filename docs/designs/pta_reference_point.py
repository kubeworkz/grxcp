def source_adds(w, kind, row="cyclefix"):
    """What a source's rows add at the end of a cycle: the cycle with them less the
    cycle with none, network by network over the draws."""
    return more(w, kind, row, "cycle8" if row.endswith("8") else "cycle")


def fresh_left():
    """What sixteen shots a row left on lines 20% off through a tile that had not
    drifted: pta_reference_fix.py's fifteen combs, their mean."""
    return fix.left(fix.fix(NOW, fix.W8))


def left_on(row, some=fix.DRAWS):
    """What a reading would leave here on the same combs: a comb is its seed's and its
    draw's, and no data set's or kind of network's."""
    xs = [c[1] for d in some for c in LINES[MNIST][REFERENCE][(row, d)]]
    return sum(xs) / len(xs)


def one_comb(col=0):
    """On how many of a read row's combs every data set and kind of network was given
    the same figure: what the probe found, or with col 1 what its reading would leave."""
    return sum(len({LINES[w][k][(row, d)][n][col] for w in WORKLOADS for k in KINDS}) == 1 for row in READ for d in DRAWS for n in range(SEEDS))


def same_as_fix(row, there):
    """Whether a row here is pta_reference_fix.py's, seed for seed, on the draws both ran."""
    return all(RUN[w][k][(row, d)] == fix.RUN[w][k][(there, d)] for w in WORKLOADS for k in KINDS for d in fix.DRAWS)


def lost_on(w, kind, row, draw):
    """What the tile costs a network in a row on one draw."""
    return stat([h - x for h, x in zip(HOSTS[w][kind], RUN[w][kind][(row, draw)])])


def clear_sets(what, kind=REFERENCE):
    """The data sets on which a figure is outside chance at one in twenty."""
    return [w for w in WORKLOADS if clear(what(w, kind))]


TRIMS = (("cycle8", "cycle"), ("cyclefix8", "cyclefix"))    # a cycle with its trim at 8 bits, and the same cycle with the finer one


def trim_costs(w, kind, pair):
    """What the trim at 8 bits costs a cycle more than the finer one."""
    return more(w, kind, pair[0], pair[1])


def trim_furthest():
    """The most the trim at 8 bits moves either cycle, in the mean, for either kind on any set."""
    return max(abs(trim_costs(w, k, pair)[0]) for w in WORKLOADS for k in KINDS for pair in TRIMS)


def trim_clear():
    """Where what it costs is outside chance at one in twenty: (data set, kind, which cycle)."""
    return [(w, k, pair[0]) for w in WORKLOADS for k in KINDS for pair in TRIMS if clear(trim_costs(w, k, pair))]


