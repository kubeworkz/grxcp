def longer(w, kind):
    """What a six-minute cycle adds over a three-minute one: each network's mean
    over its draws.  The two are read over the same probes-only rows."""
    return stat([s - t for s, t in zip(by_net(w, kind, SIX), by_net(w, kind, THREE))])


def adds_less(w, row):
    """What a row adds to a reference network over the draws, less what it adds to
    the one trained before of the same seed."""
    return stat([r - b for r, b in zip(by_net(w, REFERENCE, row), by_net(w, BEFORE, row))])


def lost_plan(w, kind, row):
    """What the tile costs a network in a row on the plan's draw alone."""
    return stat([h - x for h, x in zip(HOSTS[w][kind], RUN[w][kind][(row, PLAN)])])


def span(w, kind, row):
    """The least and the most a row adds on any one draw, the five networks' mean."""
    xs = by_draw(w, kind, row)
    return min(xs), max(xs)


def draw_se(w, kind, row):
    """The standard error of a row's mean over the draws, from the draws' own spread."""
    return draw_sd(w, kind, row) / math.sqrt(len(DRAWS))


