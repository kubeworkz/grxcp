def stat(xs):
    """Five figures' mean and standard error."""
    n = len(xs)
    m = sum(xs) / n
    return m, math.sqrt(sum((x - m) ** 2 for x in xs) / (n - 1) / n)


def spread(xs):
    """Some figures' standard deviation."""
    m = sum(xs) / len(xs)
    return math.sqrt(sum((x - m) ** 2 for x in xs) / (len(xs) - 1))


def runs(w, kind, row, draw):
    """A kind's five networks in a row on a draw: how often each is right, percent."""
    return RUN[w][kind][(row, draw)]


def partner(row, draw):
    """The row and draw a row is read over.  It meets the row's noise, but for the
    as-budgeted row of a draw, which is read over the plan's."""
    return ("budget", PLAN) if row == "budget" else (PARTNER[row], draw)


def diffs(w, kind, row, draw):
    """What a row adds on a draw over the row it is read over, network by network:
    how often right there, less in the row."""
    return [p - x for p, x in zip(RUN[w][kind][partner(row, draw)], RUN[w][kind][(row, draw)])]


def acc(w, kind, row, draw):
    """How often a kind of network is right in a row on one draw."""
    return stat(runs(w, kind, row, draw))


def adds(w, kind, row, draw):
    """What a row adds on one draw."""
    return stat(diffs(w, kind, row, draw))


def by_net(w, kind, row, what=diffs):
    """A figure for each network: its mean over the ten draws."""
    return [sum(what(w, kind, row, d)[i] for d in DRAWS) / len(DRAWS) for i in range(SEEDS)]


def by_draw(w, kind, row, what=diffs):
    """A figure for each draw: the five networks' mean."""
    return [sum(what(w, kind, row, d)) / SEEDS for d in DRAWS]


def over(w, kind, row):
    """What a row adds, over the draws: the mean, and its standard error from the
    five networks, each averaged over its ten draws."""
    return stat(by_net(w, kind, row))


def draw_sd(w, kind, row):
    """The standard deviation from draw to draw of what a row adds, the five networks' mean."""
    return spread(by_draw(w, kind, row))


def right(w, kind, row):
    """How often a kind of network is right in a row, over the draws."""
    return stat(by_net(w, kind, row, runs))


def right_sd(w, kind, row):
    """The standard deviation from draw to draw of that, the five networks' mean."""
    return spread(by_draw(w, kind, row, runs))


def lost(w, kind, row):
    """What the tile costs a network in a row, over the draws: its accuracy on its host less there."""
    return stat([h - x for h, x in zip(HOSTS[w][kind], by_net(w, kind, row, runs))])


def ahead(w, row):
    """How much more often a reference network is right in a row than the one
    trained before of the same seed, over the draws."""
    return stat([r - b for r, b in zip(by_net(w, REFERENCE, row, runs), by_net(w, BEFORE, row, runs))])


def plan_less(w, kind, row):
    """The plan's draw less a network's mean over the other nine, in how often right:
    how favourable a draw the plan's row is."""
    rest = [d for d in DRAWS if d != PLAN]
    return stat([RUN[w][kind][(row, PLAN)][i] - sum(RUN[w][kind][(row, d)][i] for d in rest) / len(rest) for i in range(SEEDS)])


def holds(w, kind, budget=WITHIN, exact=False):
    """How long a calibration holds: the longer of the intervals run whose cycle ends
    under the budget in the mean over the draws, the shorter doing so too.  Read
    on means to the hundredth, or exactly.  None if three minutes is already over."""
    ok = None
    for h in CYCLES:
        x = over(w, kind, ("cycle", h))[0]
        if (x if exact else round(x, 2)) >= budget - 1e-9:
            break
        ok = h
    return ok


def draws_over(w, kind, row, budget=WITHIN):
    """On how many of the ten draws a row adds the budget or more, the five networks' mean to the hundredth."""
    return sum(round(x, 2) >= budget - 1e-9 for x in by_draw(w, kind, row))


def from_budget(w, kind, row, budget=WITHIN):
    """What a row adds over the draws, less the budget, in its standard errors."""
    m, s = over(w, kind, row)
    return (m - budget) / s


def at_most(x, t=T95):
    """What a figure is put under, at one in twenty."""
    return x[0] + t * x[1]


def at_least(x, t=T95):
    """And over."""
    return x[0] - t * x[1]


def errors(x):
    """A difference in its own standard errors."""
    return x[0] / x[1] if x[1] else 0.0


def clear(x):
    """Whether five networks put a difference outside chance at one in twenty."""
    return abs(errors(x)) > T95


def interval(h):
    return "under 3 minutes" if h is None else minutes(h)


def pm(x):
    return f"{x[0]:.2f} +-{x[1]:.2f}"


def dpm(x):
    return f"{x[0]:+.2f} +-{x[1]:.2f}"


def r2(x):
    return round(x[0], 2), round(x[1], 2)


def section(title):
    print(f"\n{title}\n{'-' * len(title)}")


