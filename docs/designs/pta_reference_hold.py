def dac_furthest():
    """The most the DAC moves the cycle with no source, in the mean, for either kind at either interval on any set."""
    return max(abs(dac(w, k, h)[0]) for w in WORKLOADS for k in KINDS for h in CYCLES)


def dac_clear():
    """Where what the DAC costs is outside chance at one in twenty: (data set, kind, interval)."""
    return [(w, k, h) for w in WORKLOADS for k in KINDS for h in CYCLES if clear(dac(w, k, h))]


