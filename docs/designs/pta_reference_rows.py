"""
The source's rows, on the chip as it is held: which of them a cycle's end is
paying for.

B16 holds the source to three rows: its noise within 1% rms a shot for the
lines together, within 5% for a line on its own, and its lines level to 20%,
read at each calibration and corrected on the weights.  pta_reference_hold.py
found that at the end of a six-minute cycle those rows add 0.04, 0.08 and 0.17
of a point for B17's reference networks, and that on a workload that lights
most of its rows they are the larger part of what the chip loses to a cycle.
Which row it is had only been run a row at a time, on a tile that was not
calibrated, with the lines 5% off and left alone (pta_shared_row.py and the
board plan's B16).  B15 was kept at six minutes on 2026-10-10, and grx930's
harness then ran the rows apart on the chip as it is held.

MEASURED IN A MODEL, by grx930 (c930/doc/pta_error_model_design_note.md section
5, "The source's rows, on the chip as it is held", 2026-10-10; `sim/pta_mnist.sh
DIR WORK refrows`).  The working tile, 128 x 64 on two buses, at version 2.  Two
kinds of network a data set, five of each, seeds 1 to 5: the ones trained
before, and B17's reference.  Five draws, pta_reference_point.py's: draw D seeds
the tile with the network's seed and 10 D more.  Ten rows a draw:

  as budgeted     version 2 and nothing else
  probes only     a calibration's 16 probes taken and no trim written
  a cycle, no     aged six minutes, calibrated, and aged six minutes again,
  source          its trim at 8 bits
  a cycle, lit    the same with a source lit, its lines 20% off, read with
                  sixteen shots a row and corrected on the weights at 8 bits:
                  once for each of seven pairs of noise, for the lines
                  together and for a line on its own

  1% and 5%       the chip as it is held
  1% and 2%       a line's own noise tightened
  1% and 1%
  1% and none     the shared row alone
  none and 5%     a line's own noise alone
  none and none   a comb 20% off, read and corrected, and no noise
  2% and 5%       the shared row as it was before B16, -124 dB/Hz

DERIVED here:

  a row's mean and  which have to be the four tables grx930 printed, cell for
  its error         cell
  what a source     a lit cycle less the cycle with no source on the same
  adds              draws, network by network
  what a row buys   how often right in a row, less on the chip as it is held
  a row apart       what the shared row adds is the chip less the row with a
                    line's noise alone, and what a line's noise adds the chip
                    less the row with the shared row alone
  what a reading    counted: the source's noise on a shot over the root of
  should leave      the shots a line gets, and the rounding of the step

HOW SURE.  Five networks, 2.8 errors for one in twenty, as before.  Every lit
row of a draw meets the same seeds, and the rows differ in how much noise is
drawn and not in which: a row over another is closely paired.  Five draws.

WHAT THIS IS NOT.  A comb: no row here is a source that exists, and what a
row costs to meet is not said.  A level other than 20%.  An interval other
than six minutes: pta_reference_hold.py found what a source adds the same at
three.  Noise that goes with a line's own power: here it is a share of a
line's nominal light.  A calibration that sees a source's noise: the probes
are taken before the light is lit.  Version 2 and the working tile only.

Standard library only.  Run:  python3 docs/designs/pta_reference_rows.py
"""
